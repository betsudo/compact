"""Keep workspace all-features checks separate from selected Bytes proof runs."""

import os
from pathlib import Path
import subprocess
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[2]
BUILD = ROOT / 'tools/compact-rust-proof-smoke/build.rs'


class BytesProofFeatureAdmissionTests(unittest.TestCase):
    def test_broad_build_and_selected_proof_roots(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            binary = root / 'build-script'
            subprocess.run(['rustc', '--edition=2024', str(BUILD), '-o', str(binary)],
                           check=True, capture_output=True, text=True)
            generated = root / 'generated'
            contract = generated / 'contract'
            contract.mkdir(parents=True)
            for name in ('lib.rs', 'compact-rust-ir.json', 'rust-capabilities.json'):
                (contract / name).write_text('{}\n')
            base = {name: value for name, value in os.environ.items()
                    if not name.startswith('CARGO_FEATURE_') and
                    name != 'COMPACT_BYTES_REMAINING_GENERATED'}

            def run(*features, selected_root=None):
                env = dict(base)
                for feature in features:
                    env['CARGO_FEATURE_BYTES_' + feature.upper() + '_PROOF'] = '1'
                if selected_root is not None:
                    env['COMPACT_BYTES_REMAINING_GENERATED'] = str(selected_root)
                return subprocess.run([str(binary)], env=env, capture_output=True,
                                      text=True)

            broad = run('equality', 'slice')
            self.assertEqual(broad.returncode, 0, broad.stderr)
            self.assertNotIn('cargo::rustc-cfg=compact_bytes_remaining_proof_generated',
                             broad.stdout)
            for feature in ('equality', 'slice'):
                with self.subTest(feature=feature):
                    missing = run(feature)
                    self.assertNotEqual(missing.returncode, 0)
                    self.assertIn('complete Bytes generated root required', missing.stderr)
                    selected = run(feature, selected_root=generated)
                    self.assertEqual(selected.returncode, 0, selected.stderr)
                    self.assertIn('cargo::rustc-cfg=compact_bytes_remaining_proof_generated',
                                  selected.stdout)
            ambiguous = run('equality', 'slice', selected_root=generated)
            self.assertNotEqual(ambiguous.returncode, 0)
            self.assertIn('one generated Bytes proof crate per runner', ambiguous.stderr)


if __name__ == '__main__':
    unittest.main()
